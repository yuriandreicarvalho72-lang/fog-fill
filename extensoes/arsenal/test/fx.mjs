import { readFileSync } from "fs";
import { buildShot, PROFILES } from "../src/fx.js";
import { decodeCatalog } from "../src/shared.js";
const catalog = decodeCatalog(JSON.parse(readFileSync(new URL("../src/catalog.json", import.meta.url))));
const ok = (n, v, e) => console.log((JSON.stringify(v) === JSON.stringify(e) ? "ok  " : "ERRO") + " " + n + ": " + JSON.stringify(v));
ok("catálogo tem as 429 armas da planilha", catalog.length, 429);
ok("todo efeito do catálogo existe", catalog.filter((w) => !PROFILES[w.fx]).map((w) => w.n), []);
ok("todo item tem modo", catalog.filter((w) => !w.m.length).length, 0);
const glock = catalog.find((w) => w.n === "Evo Mantis");
ok("Evo Mantis: pistola, 9m/27m, pente 8", glock && [glock.fx, glock.r, glock.mag], ["pistol", [9, 27], 8]);
const s = (fx, mode, extra = {}) => buildShot({ fx, mode, from: { x: 0, y: 0 }, targets: [{ at: { x: 1500, y: 0 }, kind: "flesh" }], cell: 150, seed: 42, ...extra });
const a = s("smg", "auto"), b = s("smg", "auto");
ok("mesma semente = mesmo disparo para todos", JSON.stringify(a.elements.map((e) => e.frame((e.t0 + e.t1) / 2))) === JSON.stringify(b.elements.map((e) => e.frame((e.t0 + e.t1) / 2))), true);
const traços = (sh) => sh.elements.filter((e) => e.kind === "line" && e.frame(e.t0)?.width > 0 && e.frame(e.t0).opacity > 0.9).length;
ok("rajada = 3 traçantes", traços(s("rifle", "burst", { casings: false })), 3);
ok("pouca munição: rajada com 2 balas = 2 traçantes", traços(s("rifle", "burst", { rounds: 2, casings: false })), 2);
ok("tudo termina (sem efeito eterno)", Number.isFinite(s("smoke", "single", { smokeSec: 30 }).duration), true);
ok("fumaça dura o pedido", Math.round(s("smoke", "single", { smokeSec: 30 }).duration), 34);
const erro = s("pistol", "single", { hit: false });
ok("erro não espirra sangue", erro.elements.some((e) => e.frame(e.t1 - 0.01)?.fill === "#8a0f12"), false);
ok("sem sangue (preferência) troca por faísca", s("pistol", "single", { gore: false }).elements.some((e) => e.frame(e.t0)?.fill === "#8a0f12"), false);
ok("semiautomático não vira automático", catalog.find((w) => w.n === "Evo Mantis").m, ["single"]);
ok("rifle de assalto com rajada e automático", catalog.find((w) => w.n === "Ares Alpha Prime").m, ["single", "burst", "auto"]);
